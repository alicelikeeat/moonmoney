ALIASES = {"−": "-", "－": "-", "￥": "¥", "：": ":", "，": ",", "。": ".", "％": "%"}

def glyph_name(ch):
    return "uni%04X" % ord(ch)

def draw(rows):
    pen = TTGlyphPen(None)
    height = len(rows)
    # Rows are top-down; a 7-row glyph sits on the baseline, extra rows descend.
    for r, line in enumerate(rows):
        for c, cell in enumerate(line):
            if cell != "#":
                continue
            y_top = (7 - r) * PX
            x0, x1 = c * PX, (c + 1) * PX
            y0, y1 = y_top - PX, y_top
            pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
    width = (max(len(l) for l in rows) + 1) * PX
    return pen.glyph(), width

def build(path):
    order = [".notdef", "space"]
    glyphs, metrics, cmap = {}, {}, {}
    empty = TTGlyphPen(None).glyph()
    glyphs[".notdef"] = empty; metrics[".notdef"] = (6 * PX, 0)
    glyphs["space"] = empty; metrics["space"] = (4 * PX, 0)
    cmap[ord(" ")] = "space"
    for ch, rows in G.items():
        name = glyph_name(ch)
        g, w = draw(rows)
        glyphs[name] = g; metrics[name] = (w, 0); order.append(name)
        cmap[ord(ch)] = name
        if ch.isalpha() and ch.isascii():
            cmap[ord(ch.lower())] = name
    for alias, target in ALIASES.items():
        cmap[ord(alias)] = glyph_name(target)

    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASCENT_PX * PX, descent=-DESCENT_PX * PX)
    fb.setupNameTable({"familyName": "MoonPixel", "styleName": "Regular",
                       "uniqueFontIdentifier": "MoonPixel-Regular", "fullName": "MoonPixel Regular",
                       "psName": "MoonPixel-Regular", "version": "Version 1.0",
                       "copyright": "MoonMoney original pixel font"})
    fb.setupOS2(version=4, fsType=0, achVendID="MOON", usWeightClass=400, usWidthClass=5,
                fsSelection=0x40,  # REGULAR
                sTypoAscender=ASCENT_PX * PX, sTypoDescender=-DESCENT_PX * PX, sTypoLineGap=0,
                usWinAscent=ASCENT_PX * PX, usWinDescent=DESCENT_PX * PX, sxHeight=5 * PX, sCapHeight=7 * PX,
                ulUnicodeRange1=0b11, ulCodePageRange1=0b1)
    fb.setupPost()
    fb.save(path)

if __name__ == "__main__":
    build(sys.argv[1])
